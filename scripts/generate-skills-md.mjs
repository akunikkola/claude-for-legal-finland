#!/usr/bin/env node
// Generates SKILLS.md — a browsable index of every domain and skill.
// Reads marketplace.json (for domain order) and the frontmatter of each
// SKILL.md. Idempotent: overwrites SKILLS.md.
// Run: node scripts/generate-skills-md.mjs

import { readFileSync, writeFileSync, existsSync } from 'node:fs';
import { basename, join, relative } from 'node:path';

import { ROOT, listDirs, parseFrontmatter, readJSON, truncate } from './lib.mjs';

function fmValue(file, key) {
  return parseFrontmatter(readFileSync(file, 'utf8')).values[key] || '';
}

const trunc = (s, n = 240) => truncate(s, n);

const mp = readJSON(join(ROOT, 'marketplace.json'));

let out = `# Skills\n\n`;
out += `> Auto-generated by \`scripts/generate-skills-md.mjs\` from \`marketplace.json\`\n`;
out += `> and the frontmatter of each \`SKILL.md\`. Do not edit by hand — re-run the script.\n\n`;
out += `The collection has **${mp.plugins.length} domains**. To install, see [QUICKSTART.md](QUICKSTART.md).\n\n`;

let totalSkills = 0;
const sections = [];

for (const p of mp.plugins) {
  const skillsDir = join(ROOT, p.source, 'skills');
  const rows = [];
  if (existsSync(skillsDir)) {
    const skillDirs = listDirs(skillsDir).sort();
    for (const d of skillDirs) {
      const md = join(d, 'SKILL.md');
      if (!existsSync(md)) continue;
      const name = fmValue(md, 'name') || basename(d);
      const desc = trunc(fmValue(md, 'description'));
      const relPath = relative(ROOT, md).replace(/\\/g, '/');
      rows.push(`| [\`${name}\`](${relPath}) | ${desc} |`);
      totalSkills++;
    }
  }
  const title = p.displayName || p.name;
  let sec = `## ${title}\n\n`;
  sec += `\`/plugin install ${p.name}@${mp.name}\` – [\`${p.source}/\`](${p.source}/)\n\n`;
  if (p.description) sec += `${p.description}\n\n`;
  if (rows.length) {
    sec += `| Skill | Description |\n|---|---|\n${rows.join('\n')}\n`;
  } else {
    sec += `_No skills._\n`;
  }
  sections.push(sec);
}

out = out.replace('**' + mp.plugins.length + ' domains**', `**${mp.plugins.length} domains** and **${totalSkills} skills**`);
out += sections.join('\n');
out += `\n---\n\n*Update this file by running \`node scripts/generate-skills-md.mjs\`.*\n`;

writeFileSync(join(ROOT, 'SKILLS.md'), out);
console.log(`SKILLS.md generated: ${mp.plugins.length} domains, ${totalSkills} skills.`);
